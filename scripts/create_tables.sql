/*
  Creates staging, fact and error tables for Amazon CSV load.
  - Default design uses generic columns Col1..Col50 (NVARCHAR(4000)).
  - Staging contains BusinessKeyHash and RowHash (SHA1) used by the loader.
  IMPORTANT: adjust business key columns in the loader proc (currently Col1,Col2,Col3).
*/
SET NOCOUNT ON;

IF NOT EXISTS (SELECT 1 FROM sys.schemas WHERE name = 'dbo')
    EXEC('CREATE SCHEMA dbo');

-- Staging table
IF OBJECT_ID('dbo.stg_Amazon', 'U') IS NOT NULL
    DROP TABLE dbo.stg_Amazon;

CREATE TABLE dbo.stg_Amazon (
    LoadID INT IDENTITY(1,1) PRIMARY KEY,
    -- Generic columns for CSV columns (adjust count/types after initial import)
    Col1 NVARCHAR(4000), Col2 NVARCHAR(4000), Col3 NVARCHAR(4000), Col4 NVARCHAR(4000), Col5 NVARCHAR(4000),
    Col6 NVARCHAR(4000), Col7 NVARCHAR(4000), Col8 NVARCHAR(4000), Col9 NVARCHAR(4000), Col10 NVARCHAR(4000),
    Col11 NVARCHAR(4000), Col12 NVARCHAR(4000), Col13 NVARCHAR(4000), Col14 NVARCHAR(4000), Col15 NVARCHAR(4000),
    Col16 NVARCHAR(4000), Col17 NVARCHAR(4000), Col18 NVARCHAR(4000), Col19 NVARCHAR(4000), Col20 NVARCHAR(4000),
    Col21 NVARCHAR(4000), Col22 NVARCHAR(4000), Col23 NVARCHAR(4000), Col24 NVARCHAR(4000), Col25 NVARCHAR(4000),
    Col26 NVARCHAR(4000), Col27 NVARCHAR(4000), Col28 NVARCHAR(4000), Col29 NVARCHAR(4000), Col30 NVARCHAR(4000),
    Col31 NVARCHAR(4000), Col32 NVARCHAR(4000), Col33 NVARCHAR(4000), Col34 NVARCHAR(4000), Col35 NVARCHAR(4000),
    Col36 NVARCHAR(4000), Col37 NVARCHAR(4000), Col38 NVARCHAR(4000), Col39 NVARCHAR(4000), Col40 NVARCHAR(4000),
    Col41 NVARCHAR(4000), Col42 NVARCHAR(4000), Col43 NVARCHAR(4000), Col44 NVARCHAR(4000), Col45 NVARCHAR(4000),
    Col46 NVARCHAR(4000), Col47 NVARCHAR(4000), Col48 NVARCHAR(4000), Col49 NVARCHAR(4000), Col50 NVARCHAR(4000),
    BusinessKeyHash VARBINARY(20) NULL, -- SHA1 on business key columns (user to adjust)
    RowHash VARBINARY(20) NULL, -- SHA1 on entire row to detect changes
    LoadDate DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

-- Final / fact table with SCD Type 2 columns
IF OBJECT_ID('dbo.fct_Amazon', 'U') IS NOT NULL
    DROP TABLE dbo.fct_Amazon;

CREATE TABLE dbo.fct_Amazon (
    SurrogateKey INT IDENTITY(1,1) PRIMARY KEY,
    Col1 NVARCHAR(4000), Col2 NVARCHAR(4000), Col3 NVARCHAR(4000), Col4 NVARCHAR(4000), Col5 NVARCHAR(4000),
    Col6 NVARCHAR(4000), Col7 NVARCHAR(4000), Col8 NVARCHAR(4000), Col9 NVARCHAR(4000), Col10 NVARCHAR(4000),
    Col11 NVARCHAR(4000), Col12 NVARCHAR(4000), Col13 NVARCHAR(4000), Col14 NVARCHAR(4000), Col15 NVARCHAR(4000),
    Col16 NVARCHAR(4000), Col17 NVARCHAR(4000), Col18 NVARCHAR(4000), Col19 NVARCHAR(4000), Col20 NVARCHAR(4000),
    Col21 NVARCHAR(4000), Col22 NVARCHAR(4000), Col23 NVARCHAR(4000), Col24 NVARCHAR(4000), Col25 NVARCHAR(4000),
    Col26 NVARCHAR(4000), Col27 NVARCHAR(4000), Col28 NVARCHAR(4000), Col29 NVARCHAR(4000), Col30 NVARCHAR(4000),
    Col31 NVARCHAR(4000), Col32 NVARCHAR(4000), Col33 NVARCHAR(4000), Col34 NVARCHAR(4000), Col35 NVARCHAR(4000),
    Col36 NVARCHAR(4000), Col37 NVARCHAR(4000), Col38 NVARCHAR(4000), Col39 NVARCHAR(4000), Col40 NVARCHAR(4000),
    Col41 NVARCHAR(4000), Col42 NVARCHAR(4000), Col43 NVARCHAR(4000), Col44 NVARCHAR(4000), Col45 NVARCHAR(4000),
    Col46 NVARCHAR(4000), Col47 NVARCHAR(4000), Col48 NVARCHAR(4000), Col49 NVARCHAR(4000), Col50 NVARCHAR(4000),
    BusinessKeyHash VARBINARY(20) NULL,
    RowHash VARBINARY(20) NULL,
    IsCurrent BIT NOT NULL DEFAULT (1),
    StartDate DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    EndDate DATETIME2 NULL
);

-- Error table
IF OBJECT_ID('dbo.err_Amazon', 'U') IS NOT NULL
    DROP TABLE dbo.err_Amazon;

CREATE TABLE dbo.err_Amazon (
    ErrID INT IDENTITY(1,1) PRIMARY KEY,
    LoadDate DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    RawData NVARCHAR(MAX),
    ErrorMessage NVARCHAR(4000)
);

PRINT 'Created tables: stg_Amazon, fct_Amazon, err_Amazon';
